// ─── Registry ─────────────────────────────────────────────────────────────────

const DICTS: Record<string, Translations> = { en, es, de, pt, fr }

// Normalize a human-readable label to a translation key
export function labelToKey(label: string): string {
  return label.toLowerCase().replace(/[^a-z0-9()_-]+/g, '_').replace(/^_|_$/g, '')
}

export function getTranslation(lang: string, key: string, fallback: string): string {
  const dict = DICTS[lang] ?? DICTS['en']
  // Try exact key first
  if (dict[key] !== undefined) return dict[key]
  // Fall back to English
  if (DICTS['en'][key] !== undefined) return DICTS['en'][key]
  // Fall back to original label
  return fallback
}

export function translateLabel(lang: string, label: string): string {
  const key = labelToKey(label)
  return getTranslation(lang, key, label)
}
